#include "Chip8.h"

unsigned char fontSet[80]{
	0xF0, 0x90, 0x90, 0x90, 0xF0, // 0
	0x20, 0x60, 0x20, 0x20, 0x70, // 1
	0xF0, 0x10, 0xF0, 0x80, 0xF0, // 2
	0xF0, 0x10, 0xF0, 0x10, 0xF0, // 3
	0x90, 0x90, 0xF0, 0x10, 0x10, // 4
	0xF0, 0x80, 0xF0, 0x10, 0xF0, // 5
	0xF0, 0x80, 0xF0, 0x90, 0xF0, // 6
	0xF0, 0x10, 0x20, 0x40, 0x40, // 7
	0xF0, 0x90, 0xF0, 0x90, 0xF0, // 8
	0xF0, 0x90, 0xF0, 0x10, 0xF0, // 9
	0xF0, 0x90, 0xF0, 0x90, 0x90, // A
	0xE0, 0x90, 0xE0, 0x90, 0xE0, // B
	0xF0, 0x80, 0x80, 0x80, 0xF0, // C
	0xE0, 0x90, 0x90, 0x90, 0xE0, // D
	0xF0, 0x80, 0xF0, 0x80, 0xF0, // E
	0xF0, 0x80, 0xF0, 0x80, 0x80, // F
};

// Initializing and reseting machine
void Chip8::init() {

    PC = 0x200; // 0x200 (512) Start of most Chip-8 programs
    opcode = 0;
    I = 0;
    SP = 0;

    // Clear the display
    for (int i{0}; i < 64; ++i) {
        for (int j{0}; j < 32; ++j) {
           display[i][j] = 0; 
        }
    }

    // Clear the stack and registers V0-VF
    for (int i{0}; i < 16; ++i) {
        stack[i] = 0;
        V[i] = 0;
    }
    
    // Clear memory
    for (int i{0}; i < 4096; ++i) {
        memory[i] = 0;
    }

    // Load fonts into memory
    for (int i{0}; i < 80; ++i) {
        memory[i] = fontSet[i];
    }

    delayTimer = 0;
    soundTimer = 0;

    // Init RNG
    std::default_random_engine seed(std::chrono::system_clock::now().time_since_epoch().count());
    std::uniform_int_distribution<unsigned char> randomByte = std::uniform_int_distribution<unsigned char>(1,255U);
}